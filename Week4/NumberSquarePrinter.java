package Week4;
public class NumberSquarePrinter {
public static void main(String[] args) {
        int capSize = 10;

        for (int i = 1; i <= capSize; i++) {
            int square = i * i;
            System.out.println("Number: " + i + " | Square: " + square);
        }
    }    
}
